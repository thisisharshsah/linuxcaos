"""Generate src/font.h from the editable ASCII-art source tools/font8x16.txt.

The source lists every printable ASCII glyph (32-126) as 16 rows of 8 pixels.
`--check` exits non-zero when the committed header differs from the source.
"""

import argparse
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
FIRST_CHAR = 32
LAST_CHAR = 126
WIDTH = 8
HEIGHT = 16
LABELS = {ord('"'): "quote", ord("\\"): "backslash"}


def parse_font(text: str) -> dict[int, list[int]]:
    """Return {code: [row bytes]}; bit 7 of each row is the leftmost pixel."""
    glyphs: dict[int, list[int]] = {}
    current = None
    for lineno, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        # Pixel rows may begin with '#'; only "# ..." lines and header tails are comments.
        if line.startswith("glyph") or line == "#" or line.startswith("# "):
            line = line.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith("glyph"):
            parts = line.split()
            if len(parts) != 2 or not parts[1].isdigit():
                raise ValueError(f"line {lineno}: expected 'glyph <decimal code>'")
            code = int(parts[1])
            if not FIRST_CHAR <= code <= LAST_CHAR:
                raise ValueError(f"line {lineno}: glyph {code} outside {FIRST_CHAR}-{LAST_CHAR}")
            if code in glyphs:
                raise ValueError(f"line {lineno}: duplicate glyph {code}")
            if current is not None and len(glyphs[current]) != HEIGHT:
                raise ValueError(f"glyph {current}: expected {HEIGHT} rows, got {len(glyphs[current])}")
            glyphs[code] = []
            current = code
            continue
        if current is None:
            raise ValueError(f"line {lineno}: pixel row before any glyph header")
        if len(line) != WIDTH or set(line) - {"#", "."}:
            raise ValueError(f"line {lineno}: expected {WIDTH} characters of '#' or '.'")
        if len(glyphs[current]) == HEIGHT:
            raise ValueError(f"glyph {current}: more than {HEIGHT} rows")
        glyphs[current].append(int(line.replace("#", "1").replace(".", "0"), 2))
    if current is not None and len(glyphs[current]) != HEIGHT:
        raise ValueError(f"glyph {current}: expected {HEIGHT} rows, got {len(glyphs[current])}")
    missing = [c for c in range(FIRST_CHAR, LAST_CHAR + 1) if c not in glyphs]
    if missing:
        raise ValueError(f"missing glyphs: {missing}")
    return glyphs


def render_header(glyphs: dict[int, list[int]]) -> str:
    lines = [
        "/* SPDX-License-Identifier: GPL-2.0-or-later */",
        "/* Generated by tools/generate_font.py - DO NOT EDIT MANUALLY */",
        "#ifndef FONT_H",
        "#define FONT_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define FONT_FIRST_CHAR {FIRST_CHAR}",
        f"#define FONT_LAST_CHAR  {LAST_CHAR}",
        f"#define FONT_WIDTH      {WIDTH}",
        f"#define FONT_HEIGHT     {HEIGHT}",
        "",
        f"static const uint8_t font8x16[{LAST_CHAR - FIRST_CHAR + 1}][{HEIGHT}] = {{",
    ]
    for code in range(FIRST_CHAR, LAST_CHAR + 1):
        label = LABELS.get(code, chr(code))
        values = ", ".join(f"0x{v:02x}" for v in glyphs[code])
        lines.append(f"    /* {code:3d} '{label}' */ {{ {values} }},")
    lines += ["};", "", "#endif /* FONT_H */", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, default=ROOT / "tools/font8x16.txt")
    parser.add_argument("--output", type=Path, default=ROOT / "src/font.h")
    parser.add_argument("--check", action="store_true", help="verify the header is current; write nothing")
    args = parser.parse_args(argv)
    try:
        header = render_header(parse_font(args.source.read_text(encoding="ascii")))
    except (OSError, ValueError) as exc:
        print(f"generate_font: {exc}", file=sys.stderr)
        return 1
    if args.check:
        current = args.output.read_text(encoding="ascii") if args.output.exists() else ""
        if current != header:
            print(f"generate_font: {args.output} is stale; run `make font`", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(header, encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""Decode an original M1 entry-probe record from a saved file.

This tool never reads live memory. A syntactically valid record does not establish
its origin: the same bytes can be generated by an emulator or by hand.
"""

import argparse
import json
import struct
from pathlib import Path


MAGIC = b"M1PROBE\x00"
VERSION = 1
RECORD_SIZE = 96
RECORD_LAYOUT = struct.Struct("<8sII10Q")
EVIDENCE_NOTE = (
    "Untrusted evidence: a valid record is not proof of Apple execution or "
    "hardware compatibility. Pending records contain no completed capture."
)


def decode_record(data: bytes) -> dict:
    """Validate and decode exactly one little-endian version-1 record."""
    if len(data) != RECORD_SIZE:
        raise ValueError(f"Expected exactly {RECORD_SIZE} record bytes; got {len(data)}")
    magic, version, size, status, *values = RECORD_LAYOUT.unpack(data)
    if magic != MAGIC:
        raise ValueError("Invalid probe record magic")
    if version != VERSION:
        raise ValueError(f"Unsupported probe record version: {version}")
    if size != RECORD_SIZE:
        raise ValueError(f"Invalid probe record size: {size}")
    if status not in (0, 1):
        raise ValueError(f"Unknown probe record status: {status}")

    x0, x1, x2, x3, incoming_sp, entry_pc, current_el, daif, reserved = values
    if reserved:
        raise ValueError("Probe record reserved field must be zero")
    if status == 1:
        if current_el not in (4, 8, 12):
            raise ValueError(f"Invalid captured CurrentEL value: {current_el:#x}")
        if daif & ~0x3C0:
            raise ValueError(f"Invalid captured DAIF value: {daif:#x}")

    return {
        "version": version,
        "size": size,
        "status": "captured" if status == 1 else "pending",
        "x0": hex(x0),
        "x1": hex(x1),
        "x2": hex(x2),
        "x3": hex(x3),
        "incoming_sp": hex(incoming_sp),
        "entry_pc": hex(entry_pc),
        "current_el": hex(current_el),
        "exception_level": current_el >> 2 if status == 1 else None,
        "daif": hex(daif),
        "evidence_note": EVIDENCE_NOTE,
    }


def nonnegative_offset(value: str) -> int:
    """Accept decimal offsets and explicit Python-style integer prefixes."""
    try:
        offset = int(value, 0)
    except ValueError as exc:
        raise argparse.ArgumentTypeError("offset must be an integer (e.g. 96 or 0x60)") from exc
    if offset < 0:
        raise argparse.ArgumentTypeError("offset must be nonnegative")
    return offset


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("path", type=Path, help="saved probe record or binary memory dump")
    parser.add_argument(
        "--offset", type=nonnegative_offset, default=0,
        help="byte offset of the record inside the file (default: 0)",
    )
    args = parser.parse_args(argv)
    try:
        with args.path.open("rb") as source:
            source.seek(args.offset)
            record = decode_record(source.read(RECORD_SIZE))
    except (OSError, OverflowError, ValueError) as exc:
        parser.error(str(exc))
    print(json.dumps(record, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
